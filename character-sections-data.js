const CHARACTER_SECTION_KEYS = ['background', 'anecdotes', 'notes'];

function getCharacterSection(key, characterId) {
  const group = CHARACTER_SECTIONS_DB[key];
  if (!group) return null;
  return group[characterId] || null;
}

function foldBlocksByHeading(blocks) {
  if (!blocks || !blocks.length) return [];

  const result = [];
  let index = 0;

  while (index < blocks.length) {
    const block = blocks[index];
    if (block.type !== 'heading') {
      result.push(block);
      index += 1;
      continue;
    }

    const inner = [];
    index += 1;
    while (index < blocks.length && blocks[index].type !== 'heading') {
      inner.push(blocks[index]);
      index += 1;
    }

    result.push({
      type: 'fold',
      title: block.text,
      blocks: inner,
    });
  }

  return result;
}

function renderCharacterBlocks(blocks, options = {}) {
  if (!blocks || !blocks.length) return '';

  const source = options.foldByHeading ? foldBlocksByHeading(blocks) : blocks;

  return source
    .map((block) => {
      switch (block.type) {
        case 'subtitle':
          return `<h3 class="character-section__subtitle">${block.text}</h3>`;
        case 'rule':
          return '<hr class="character-section__rule">';
        case 'heading':
          return `<h4 class="character-section__heading">${block.text}</h4>`;
        case 'p':
          return `<p>${block.text}</p>`;
        case 'list': {
          const tag = block.ordered ? 'ol' : 'ul';
          const items = block.items.map((item) => `<li>${item}</li>`).join('');
          return `<${tag} class="character-section__list">${items}</${tag}>`;
        }
        case 'collapse': {
          const inner = renderCharacterBlocks(block.blocks || []);
          return `
            <details class="character-section__collapse">
              <summary class="character-section__collapse-summary">${block.summary || '展開內容'}</summary>
              <div class="character-section__collapse-body">
                ${inner}
              </div>
            </details>
          `;
        }
        case 'fold': {
          const inner = renderCharacterBlocks(block.blocks || []);
          return `
            <details class="character-section__fold">
              <summary class="character-section__fold-summary">
                <span class="character-section__fold-title">${block.title || ''}</span>
                <span class="character-section__fold-arrow" aria-hidden="true"></span>
              </summary>
              <div class="character-section__fold-body">
                ${inner}
              </div>
            </details>
          `;
        }
        case 'quote': {
          const textHtml = block.html || block.text || '';
          const attribution = block.attribution
            ? `<figcaption class="character-section__quote-attr">—— ${block.attribution}</figcaption>`
            : '';
          return `
            <figure class="quote-card character-section__quote">
              <span class="quote-card__mark" aria-hidden="true">「</span>
              <blockquote class="quote-card__text">${textHtml}</blockquote>
              <span class="quote-card__close" aria-hidden="true">」</span>
              ${attribution}
            </figure>
          `;
        }
        case 'figure': {
          const caption = block.caption
            ? `<figcaption class="character-section__figure-caption">${block.caption}</figcaption>`
            : '';
          const artistName = block.artist
            ? block.artistUrl
              ? `<a href="${block.artistUrl}" class="artist-drawer__link" target="_blank" rel="noopener noreferrer">${block.artist}</a>`
              : `<span class="artist-drawer__name">${block.artist}</span>`
            : '';
          const artistDrawer = block.artist
            ? `<div class="artist-drawer">
                <p class="artist-drawer__text">
                  繪師：${artistName}
                </p>
              </div>`
            : '';
          return `
            <figure class="character-section__figure">
              <div class="character-section__figure-media${block.artist ? ' character-intro__media' : ''}">
              <img src="${typeof siteUrl === 'function' ? siteUrl(block.src || '') : (block.src || '')}" alt="${block.alt || ''}" class="character-section__figure-img">
                ${artistDrawer}
              </div>
              ${caption}
            </figure>
          `;
        }
        case 'dialogue': {
          const lines = (block.lines || [])
            .map((line) => {
              if (line.narration) {
                const speaker = line.speaker
                  ? `<strong class="character-section__dialogue-speaker">${line.speaker}</strong>`
                  : '';
                return `<p class="character-section__dialogue-line character-section__dialogue-line--narration">${speaker}${line.text}</p>`;
              }
              return `<p class="character-section__dialogue-line"><strong class="character-section__dialogue-speaker">${line.speaker}</strong>：${line.text}</p>`;
            })
            .join('');
          return `<div class="character-section__dialogue">${lines}</div>`;
        }
        case 'drawer': {
          const inner = renderCharacterBlocks(block.blocks || []);
          const hint = block.hint || '展開以觀看全文';
          const warn = block.tooltip || '涉及據透，請注意';
          return `
            <details class="character-section__drawer">
              <summary class="character-section__drawer-summary">
                <h3 class="character-section__subtitle">${block.title || ''}</h3>
                <hr class="character-section__rule">
                <span class="character-section__drawer-hint">
                  <span class="character-section__drawer-hint-text">
                    <span class="character-section__drawer-hint-main">${hint}</span>
                    <span class="character-section__drawer-hint-warn">${warn}</span>
                  </span>
                  <span class="character-section__drawer-arrow" aria-hidden="true"></span>
                </span>
              </summary>
              <div class="character-section__drawer-body">
                ${inner}
                <button type="button" class="character-section__drawer-close" data-drawer-close>
                  <span class="character-section__drawer-close-text">收起全文</span>
                  <span class="character-section__drawer-arrow character-section__drawer-arrow--up" aria-hidden="true"></span>
                </button>
              </div>
            </details>
          `;
        }
        default:
          return '';
      }
    })
    .join('');
}

document.addEventListener('click', (event) => {
  const closeBtn = event.target.closest('[data-drawer-close]');
  if (!closeBtn) return;
  const drawer = closeBtn.closest('details.character-section__drawer');
  if (drawer) drawer.open = false;
});
